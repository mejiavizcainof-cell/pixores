import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = path.resolve(import.meta.dirname, "..");
const catalogPath = path.join(projectRoot, "src", "fonts", "pixores-fonts.ts");
const outputDirectory = path.join(projectRoot, "public", "video-maker-assets", "fonts");

function slugify(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function readGoogleFontNames(source) {
  const groups = [...source.matchAll(/label:\s*"([^"]+)"[\s\S]*?fonts:\s*\[([\s\S]*?)\]/g)];
  return [...new Set(groups
    .filter((match) => match[1] !== "System Fonts")
    .flatMap((match) => [...match[2].matchAll(/"([^"]+)"/g)].map((font) => font[1])))];
}

function getLatinFace(css) {
  const latinBlocks = [...css.matchAll(/\/\*\s*latin\s*\*\/\s*(@font-face\s*\{[\s\S]*?\})/g)];
  const block = latinBlocks.at(-1)?.[1] || css.match(/@font-face\s*\{[\s\S]*?\}/)?.[0];
  const url = block?.match(/src:\s*url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
  if (!block || !url) throw new Error("Google Fonts did not return a usable latin WOFF2 face.");
  return { block, url };
}

async function downloadFont(fontFamily) {
  const queryName = encodeURIComponent(fontFamily).replace(/%20/g, "+");
  const response = await fetch(`https://fonts.googleapis.com/css2?family=${queryName}&display=swap`, {
    headers: {
      "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/126 Safari/537.36",
    },
  });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
  const { block, url } = getLatinFace(await response.text());
  const fontResponse = await fetch(url);
  if (!fontResponse.ok) throw new Error(`${fontResponse.status} ${fontResponse.statusText}`);
  const fileName = `${slugify(fontFamily)}.woff2`;
  await writeFile(path.join(outputDirectory, fileName), Buffer.from(await fontResponse.arrayBuffer()));
  const normalizedFace = block
    .replace(/src:\s*url\([^)]+\)\s*format\('woff2'\);/, `src: url('./${fileName}') format('woff2');`)
    .replace(/font-display:\s*swap;/, "font-display: block;");
  return normalizedFace;
}

const catalog = await readFile(catalogPath, "utf8");
const fontFamilies = readGoogleFontNames(catalog);
if (!fontFamilies.length) throw new Error("No Pixores Google fonts were found in the catalog.");

await mkdir(outputDirectory, { recursive: true });
const faces = [];
for (const [index, fontFamily] of fontFamilies.entries()) {
  process.stdout.write(`[${index + 1}/${fontFamilies.length}] ${fontFamily}\n`);
  try {
    faces.push(await downloadFont(fontFamily));
  } catch (error) {
    throw new Error(`Unable to package ${fontFamily}: ${error instanceof Error ? error.message : error}`);
  }
}

const banner = [
  "/* Generated by scripts/sync-pixores-fonts.mjs.",
  " * Font files are distributed by Google Fonts under their respective open font licenses.",
  " * Keep rendering offline: do not replace these URLs with remote providers.",
  " */",
].join("\n");
await writeFile(path.join(outputDirectory, "pixores-fonts.css"), `${banner}\n\n${faces.join("\n\n")}\n`, "utf8");
await writeFile(path.join(outputDirectory, "README.md"), [
  "# Pixores packaged fonts",
  "",
  "These WOFF2 files are generated from the Pixores font catalog with `npm run fonts:sync`.",
  "They originate from Google Fonts and retain the open font license assigned to each family.",
  "See https://fonts.google.com/attribution for family attribution and license details.",
  "Rendering must use this local stylesheet so desktop exports never depend on Internet access.",
  "",
].join("\n"), "utf8");

process.stdout.write(`Packaged ${fontFamilies.length} Pixores fonts in ${outputDirectory}.\n`);
